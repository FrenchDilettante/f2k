//! The C library's memory routines the compiler lowers to on the target: `memcmp`, `memset`,
//! `memcpy` and `memmove`, in assembly.
//!
//! Target only: host builds (the unit tests) link the host's C library, whose routines these must
//! not replace.

// The string instructions, one `rep` each. They must not be Rust loops: the kernel crate builds
// unoptimized under every test profile (see Cargo.toml), where a `for` over `ptr::add` costs a
// range step and two precondition checks per byte — every struct move goes through these symbols,
// so a byte loop makes a thread's creation take milliseconds.
core::arch::global_asm!(
    // memcmp: `repe cmpsb` runs to the first differing byte or the end. On a difference the two
    // pointers stand one past it, and the result is the first block's byte less the second's,
    // both unsigned, so its sign is memcmp's. A zero length compares nothing and leaves the flags
    // alone, so it is answered before the compare.
    ".section .text.memcmp, \"ax\"",
    ".global memcmp",
    ".type memcmp, @function",
    "memcmp:",
    "    push esi",
    "    push edi",
    "    mov esi, [esp + 12]",
    "    mov edi, [esp + 16]",
    "    mov ecx, [esp + 20]",
    "    xor eax, eax",
    "    test ecx, ecx",
    "    jz 2f",
    "    cld",
    "    repe cmpsb",
    "    je 2f",
    "    movzx eax, byte ptr [esi - 1]",
    "    movzx ecx, byte ptr [edi - 1]",
    "    sub eax, ecx",
    "2:",
    "    pop edi",
    "    pop esi",
    "    ret",
    ".size memcmp, . - memcmp",
    ".section .text.memset, \"ax\"",
    ".global memset",
    ".type memset, @function",
    "memset:",
    "    push edi",
    "    mov edi, [esp + 8]",
    "    mov eax, [esp + 12]",
    "    mov ecx, [esp + 16]",
    "    cld",
    "    rep stosb",
    "    mov eax, [esp + 8]",
    "    pop edi",
    "    ret",
    ".size memset, . - memset",
    ".section .text.memcpy, \"ax\"",
    ".global memcpy",
    ".type memcpy, @function",
    "memcpy:",
    "    push esi",
    "    push edi",
    "    mov edi, [esp + 12]",
    "    mov esi, [esp + 16]",
    "    mov ecx, [esp + 20]",
    "    cld",
    "    rep movsb",
    "    mov eax, [esp + 12]",
    "    pop edi",
    "    pop esi",
    "    ret",
    ".size memcpy, . - memcpy",
    // memmove (what `ptr::copy` and `copy_within` with a non-constant length lower to): forwards
    // unless the destination starts inside the source, then backwards from the last byte with the
    // direction flag set (and cleared again: the kernel runs with it clear).
    ".section .text.memmove, \"ax\"",
    ".global memmove",
    ".type memmove, @function",
    "memmove:",
    "    push esi",
    "    push edi",
    "    mov edi, [esp + 12]",
    "    mov esi, [esp + 16]",
    "    mov ecx, [esp + 20]",
    "    mov eax, edi",
    "    sub eax, esi",
    "    cmp eax, ecx",
    "    jb 2f",
    "    cld",
    "    rep movsb",
    "    jmp 3f",
    "2:",
    "    lea esi, [esi + ecx - 1]",
    "    lea edi, [edi + ecx - 1]",
    "    std",
    "    rep movsb",
    "    cld",
    "3:",
    "    mov eax, [esp + 12]",
    "    pop edi",
    "    pop esi",
    "    ret",
    ".size memmove, . - memmove",
);
