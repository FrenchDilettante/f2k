#!/usr/bin/env python3
"""
Generate rtl's single-byte code page tables (userland/rtl/src/codepage/tables.rs): code page 850's
high half, and the best-fit tables WideCharToMultiByte falls back on for 1252, 437, 850 and 28591.

The sources are public data, read from the files given (download them first):
  bestfit1252.txt         Microsoft's best-fit table for 1252, as unicode.org publishes it
                          (Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/): its WCTABLE, less the
                          entries its MBTABLE round-trips.
  windows-437-2000.ucm    ICU's tables taken from Windows 2000 itself through IMultiLanguage
  windows-850-2000.ucm    (unicode-org/icu-data, charset/data/ucm/): each |0 line is an exact
  windows-28591-2000.ucm  mapping, each |1 line a best fit. Microsoft publishes no bestfit*.txt
                          for the OEM and ISO pages.

A best-fit table is two arrays, the units ascending and the byte each becomes, which the conversion
searches; the units a page holds exactly are not in it.

Usage:
  gen-codepages.py <dir holding the four files> [<output>]
      (default output: userland/rtl/src/codepage/tables.rs)
"""
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "userland" / "rtl" / "src" / "codepage" / "tables.rs"


def read_ucm(path):
    """A ucm file's exact (|0) and best-fit (|1) mappings, unit to byte."""
    exact, fit = {}, {}
    for line in path.read_text(encoding="latin-1").splitlines():
        m = re.match(r"<U([0-9A-F]{4})>\s+\\x([0-9A-F]{2})\s+\|([01])", line)
        if m:
            (exact if m[3] == "0" else fit)[int(m[1], 16)] = int(m[2], 16)
    return exact, fit


def read_bestfit(path, tag):
    """A bestfit*.txt section's records, as (first, second) pairs."""
    pairs, inside = [], False
    for line in path.read_text(encoding="latin-1").splitlines():
        fields = line.split(";")[0].split()
        if not fields:
            continue
        if fields[0] == tag:
            inside = True
        elif inside and fields[0].startswith("0x"):
            pairs.append((int(fields[0], 16), int(fields[1], 16)))
        elif inside:
            break
    return pairs


def rows(values, per_line, fmt, indent="    "):
    out = []
    for i in range(0, len(values), per_line):
        out.append(indent + " ".join(fmt.format(v) + "," for v in values[i:i + per_line]))
    return "\n".join(out)


def best_fit(name, page, fit):
    units = sorted(fit)
    return (
        f"/// Code page {page}'s best fit: the units it does not hold, ascending, and the bytes they\n"
        "/// become.\n"
        "#[rustfmt::skip]\n"
        f"pub static {name}: BestFit = BestFit {{\n"
        f"    units: &[\n{rows(units, 11, '0x{:04X}', ' ' * 8)}\n    ],\n"
        f"    bytes: &[\n{rows([fit[u] for u in units], 15, '0x{:02X}', ' ' * 8)}\n    ],\n"
        "};\n"
    )


def main():
    source = Path(sys.argv[1])
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else OUTPUT

    mb = dict(read_bestfit(source / "bestfit1252.txt", "MBTABLE"))
    wc = read_bestfit(source / "bestfit1252.txt", "WCTABLE")
    fit_1252 = {unit: byte for unit, byte in wc if mb.get(byte) != unit}

    exact_437, fit_437 = read_ucm(source / "windows-437-2000.ucm")
    exact_850, fit_850 = read_ucm(source / "windows-850-2000.ucm")
    exact_28591, fit_28591 = read_ucm(source / "windows-28591-2000.ucm")
    assert all(exact_28591.get(b) == b for b in range(256)), "28591 is Latin-1"
    high_850 = {byte: unit for unit, byte in exact_850.items() if byte >= 0x80}
    assert sorted(high_850) == list(range(0x80, 0x100)), "850 maps every high byte"

    text = (
        "//! Generated by scripts/gen-codepages.py from Microsoft's bestfit1252.txt and ICU's\n"
        "//! windows-437-2000, windows-850-2000 and windows-28591-2000 tables (taken from Windows 2000):\n"
        "//! do not edit.\n\n"
        "use super::sbcs::BestFit;\n\n"
        "/// Code page 850's high half (0x80-0xFF) as UTF-16.\n"
        "#[rustfmt::skip]\n"
        f"pub const CP850_HIGH: [u16; 128] = [\n{rows([high_850[b] for b in range(0x80, 0x100)], 12, '0x{:04X}')}\n];\n\n"
    )
    for name, page, fit in [
        ("FIT_1252", 1252, fit_1252),
        ("FIT_437", 437, fit_437),
        ("FIT_850", 850, fit_850),
        ("FIT_28591", 28591, fit_28591),
    ]:
        text += best_fit(name, page, fit) + "\n"
    output.write_text(text.rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
