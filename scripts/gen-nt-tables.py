#!/usr/bin/env python3
"""
Regenerate the Windows 2000 tables F2K takes from public sources (ARCH-6):

  userland/ntdll/w2k-services.txt   the system-service numbers (KiServiceTable order) of Windows
                                    2000's ntoskrnl, which ntdll's Nt*/Zw* stubs load into EAX
  userland/rtl/src/status_table.rs  RtlNtStatusToDosError's NTSTATUS -> Win32 error table

Sources (pinned by commit; the script downloads them unless given local copies):

  - j00ru, "Windows X86 System Call Table (NT/2000/XP/2003/Vista/7/8/10)",
    https://github.com/j00ru/windows-syscalls, x86/json/nt-per-system.json, "Windows 2000" (the
    numbers are the same in SP0 through SP4; the capture machine runs SP4).
  - Wine, dlls/ntdll/error.h (the table generated by its make_errors tool), include/winerror.h and
    include/ntstatus.h (the codes' values; a few statuses map to themselves), https://github.com/wine-mirror/wine. Wine's table describes later
    Windows releases too: only the facilities Windows 2000 defines are kept (see FACILITIES), and
    the entries are unverified against Windows 2000's own (GAP-NT-3's companion, GAP-NT-5).

Usage:
  gen-nt-tables.py [--syscalls nt-per-system.json] [--wine-error error.h] [--winerror winerror.h]
                   [--ntstatus ntstatus.h]
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SYSCALLS_COMMIT = "8a6806ac9148633e8afbbdb42e6002930b002741"
WINE_COMMIT = "72fd6e925179ee064f9535c34e3f621822a8d97d"
SYSCALLS_URL = f"https://raw.githubusercontent.com/j00ru/windows-syscalls/{SYSCALLS_COMMIT}/x86/json/nt-per-system.json"
WINE_ERROR_URL = f"https://raw.githubusercontent.com/wine-mirror/wine/{WINE_COMMIT}/dlls/ntdll/error.h"
WINERROR_URL = f"https://raw.githubusercontent.com/wine-mirror/wine/{WINE_COMMIT}/include/winerror.h"
NTSTATUS_URL = f"https://raw.githubusercontent.com/wine-mirror/wine/{WINE_COMMIT}/include/ntstatus.h"
# NTSTATUS facilities Windows 2000 defines: the base codes, the debugger's, RPC's (runtime and
# stubs), and the terminal server's.
FACILITIES = {0x000, 0x001, 0x002, 0x003, 0x00A}


def fetch(path, url):
    if path:
        return Path(path).read_text(encoding="utf-8")
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def services(text):
    table = json.loads(text)["Windows 2000"]
    numbers = table["SP4"]
    for pack, other in table.items():
        if other != numbers:
            sys.exit(f"Windows 2000 {pack}'s numbers differ from SP4's: pick one")
    lines = [
        "# Windows 2000's system services, by number (KiServiceTable order; identical from SP0 to SP4).",
        "# Generated by scripts/gen-nt-tables.py from j00ru's table",
        f"# (github.com/j00ru/windows-syscalls@{SYSCALLS_COMMIT[:12]}, x86/json/nt-per-system.json):",
        "# unverified against the capture machine's own ntdll until FU-1's disassembly (GAP-NT-3).",
    ]
    for name, number in sorted(numbers.items(), key=lambda item: item[1]):
        lines.append(f"{number:#05x} {name}")
    return "\n".join(lines) + "\n"


def error_values(text):
    values = {}
    for match in re.finditer(r"^#define\s+(\w+)\s+\(\(NTSTATUS\)\s*(0x[0-9A-Fa-f]+)L?\)", text, re.M):
        values[match.group(1)] = int(match.group(2), 16)
    for match in re.finditer(r"^#define\s+(\w+)\s+(\S+)", text, re.M):
        name, value = match.groups()
        value = value.strip("()").rstrip("L")
        try:
            values[name] = int(value, 0)
        except ValueError:
            pass
    # Symbols defined through other symbols (or _HRESULT_TYPEDEF_ wrappers) resolve once.
    for match in re.finditer(r"^#define\s+(\w+)\s+_HRESULT_TYPEDEF_\((0x[0-9A-Fa-f]+)L?\)", text, re.M):
        values.setdefault(match.group(1), int(match.group(2), 16))
    for match in re.finditer(r"^#define\s+(\w+)\s+(\w+)\s*$", text, re.M):
        name, other = match.groups()
        if name not in values and other in values:
            values[name] = values[other]
    return values


def status_table(error_h, winerror_h, ntstatus_h):
    values = error_values(winerror_h + "\n" + ntstatus_h)
    entries = re.findall(r"^\s+(\w+),\s+/\* ([0-9a-f]{8})", error_h, re.M)
    pairs = []
    for symbol, status in entries:
        status = int(status, 16)
        if (status >> 16) & 0xFFF not in FACILITIES:
            continue
        if symbol not in values:
            sys.exit(f"winerror.h has no value for {symbol} (status {status:#010x})")
        error = values[symbol]
        if error == 317 and symbol == "ERROR_MR_MID_NOT_FOUND":
            continue  # no mapping: the lookup's default
        pairs.append((status, error))
    pairs.sort()
    # Runs of consecutive statuses become ranges: (first status, count, offset into ERRORS).
    ranges, errors = [], []
    for status, error in pairs:
        if ranges and ranges[-1][0] + ranges[-1][1] == status:
            ranges[-1][1] += 1
        else:
            ranges.append([status, 1, len(errors)])
        errors.append(error)
    width = max(errors).bit_length()
    kind = "u16" if width <= 16 else "u32"
    out = [
        "//! RtlNtStatusToDosError's table: the Win32 error each NTSTATUS maps to, for the facilities",
        "//! Windows 2000 defines. Generated by scripts/gen-nt-tables.py from Wine's table",
        f"//! (github.com/wine-mirror/wine@{WINE_COMMIT[:12]}, dlls/ntdll/error.h and include/winerror.h);",
        "//! unverified against Windows 2000's own (GAP-NT-5). Do not edit: regenerate.",
        "",
        "/// Runs of consecutive statuses: (the first status, how many, their first error's index in",
        "/// [`ERRORS`]), in status order.",
        "#[rustfmt::skip]",
        f"pub const RANGES: [(u32, u16, u16); {len(ranges)}] = [",
    ]
    for start, count, offset in ranges:
        out.append(f"    ({start:#010x}, {count}, {offset}),")
    out += [
        "];",
        "",
        "/// The errors, run by run.",
        "#[rustfmt::skip]",
        f"pub const ERRORS: [{kind}; {len(errors)}] = [",
    ]
    for at in range(0, len(errors), 12):
        out.append("    " + " ".join(f"{e}," for e in errors[at:at + 12]))
    out.append("];")
    return "\n".join(out) + "\n", kind


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--syscalls")
    parser.add_argument("--wine-error")
    parser.add_argument("--winerror")
    parser.add_argument("--ntstatus")
    args = parser.parse_args()
    (REPO / "userland/ntdll/w2k-services.txt").write_text(services(fetch(args.syscalls, SYSCALLS_URL)))
    table, _ = status_table(
        fetch(args.wine_error, WINE_ERROR_URL), fetch(args.winerror, WINERROR_URL), fetch(args.ntstatus, NTSTATUS_URL)
    )
    (REPO / "userland/rtl/src/status_table.rs").write_text(table)


if __name__ == "__main__":
    main()
