#!/usr/bin/env python3
"""
Generate kernel32's sort-key weights (userland/kernel32/src/locale/sortkey/weights.rs) from Microsoft's
published "Windows NT 4.0 through Windows Server 2003 Sorting Weight Table.txt" (the Sorting
Weight Tables download, https://www.microsoft.com/download/details.aspx?id=10921; MS-UCODEREF names
it the table Windows 2000 sorts by).

What it keeps:
  - the default table's weights (SORTKEY: script member, alphabetic, diacritic and case weight) of
    the scripts in COVERED, as runs: a run is consecutive code points whose weights are the same
    but for an alphabetic weight one higher each;
  - the default expansions (EXPANSION: æ sorts as "ae"), less the German phonebook's, which the
    table marks as not used by default;
  - the locales whose diacritics sort from the end (REVERSEDIACRITICS: French).
The ideographs, Hangul and the other scripts past COVERED are left out, as are the locales' own
compressions and exceptions (the Czech "ch", the Danish "aa"...).

Usage:
  gen-sortkeys.py <the table's .txt> [<output>]
"""
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "userland" / "kernel32" / "src" / "locale" / "sortkey" / "weights.rs"

# The code points whose weights are kept: Latin, IPA, the spacing and combining marks, Greek,
# Cyrillic, Armenian; Latin Extended Additional and Greek Extended; the general punctuation, the
# currency symbols, the letterlike symbols; the halfwidth and fullwidth forms.
COVERED = [
    (0x0000, 0x0590),
    (0x1E00, 0x2070),
    (0x20A0, 0x20D0),
    (0x2100, 0x2150),
    (0xFF00, 0xFFF0),
]


def sections(path):
    """The table's lines, each one's fields (its comment dropped), with the section they are in."""
    section = None
    for line in path.read_text(encoding="latin-1").splitlines():
        fields = line.split(";")[0].split()
        if not fields:
            continue
        if fields[0] in ("SORTKEY", "ENDSORTKEY", "SORTTABLES", "REVERSEDIACRITICS",
                         "DOUBLECOMPRESSION", "MULTIPLEWEIGHTS", "EXPANSION", "COMPATIBILITY",
                         "COMPRESSION", "EXCEPTION", "JAMOSORT", "ENDSORTTABLES"):
            section = fields[0]
            continue
        yield section, fields, line


def rows(values, per_line, fmt, indent=" " * 8):
    return "\n".join(
        indent + " ".join(fmt.format(v) + "," for v in values[i:i + per_line])
        for i in range(0, len(values), per_line)
    )


def main():
    source = Path(sys.argv[1])
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else OUTPUT
    weights, expansions, reversed_lcids = {}, [], []
    for section, fields, line in sections(source):
        if section == "SORTKEY" and fields[0].startswith("0x") and len(fields) == 5:
            weights[int(fields[0], 16)] = tuple(int(f) for f in fields[1:])
        elif section == "EXPANSION" and len(fields) == 3 and "NOT USED IN DEFAULT" not in line:
            expansions.append(tuple(int(f, 16) for f in fields))
        elif section == "REVERSEDIACRITICS" and fields[0].startswith("0x"):
            reversed_lcids.append(int(fields[0], 16))

    kept = sorted(c for c in weights if any(a <= c < b for a, b in COVERED))
    runs = []
    for c in kept:
        sm, aw, dw, cw = weights[c]
        if runs:
            first, n, (rsm, raw, rdw, rcw) = runs[-1]
            if c == first + n and (sm, aw, dw, cw) == (rsm, raw + n, rdw, rcw) and n < 255:
                runs[-1][1] += 1
                continue
        runs.append([c, 1, (sm, aw, dw, cw)])
    expansions.sort()

    text = (
        "//! Generated by scripts/gen-sortkeys.py from Microsoft's \"Windows NT 4.0 through Windows\n"
        "//! Server 2003 Sorting Weight Table\": do not edit.\n\n"
        f"/// The first code point of each run of weights ({len(runs)} runs over {len(kept)} code points).\n"
        "#[rustfmt::skip]\n"
        f"pub static FIRST: [u16; {len(runs)}] = [\n{rows([r[0] for r in runs], 12, '0x{:04X}', '    ')}\n];\n\n"
        "/// Each run's length, and its first code point's script member, alphabetic, diacritic and\n"
        "/// case weights.\n"
        "#[rustfmt::skip]\n"
        f"pub static RUNS: [[u8; 5]; {len(runs)}] = [\n"
        + rows([f"[{n}, {sm}, {aw}, {dw}, {cw}]" for _, n, (sm, aw, dw, cw) in runs], 4, "{}", "    ")
        + "\n];\n\n"
        "/// The default expansions: a character, and the two it sorts as.\n"
        "#[rustfmt::skip]\n"
        f"pub static EXPANSIONS: [(u16, u16, u16); {len(expansions)}] = [\n"
        + "\n".join(f"    (0x{a:04X}, 0x{b:04X}, 0x{c:04X})," for a, b, c in expansions)
        + "\n];\n\n"
        "/// The locales whose diacritic weights run from the string's end.\n"
        f"pub static REVERSE_DIACRITICS: [u32; {len(reversed_lcids)}] = [\n"
        + rows(sorted(reversed_lcids), 6, "0x{:04X}", "    ")
        + "\n];\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text)


if __name__ == "__main__":
    main()
