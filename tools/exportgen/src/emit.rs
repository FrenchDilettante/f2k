//! What the specs generate: Rust tables for the kernel (the NT service table, the DLLs' declared
//! exports), and each system DLL's system-service stubs and module-definition (`.def`) file.

use std::fmt::Write;

use crate::{w2k, ArgKind, Export, Implementation, Spec};

/// The line every generated Rust file starts with.
fn banner(source: &str) -> String {
    format!("// Generated by exportgen from {source}: edit the spec, not this file.\n\n")
}

fn quote(text: &str) -> String {
    format!("{text:?}")
}

/// The kernel's NT service table over ntdll's spec: `NT_SERVICE_LIMIT` (Windows 2000's
/// KiServiceLimit) and `NT_SERVICES`, one `(number, service, argument bytes, handler)` entry per
/// system service the spec declares, in number order, each handler a generated wrapper (below):
/// decode the argument block by the spec's kinds, call the typed handler with the call's context
/// first, and put its NTSTATUS in EAX ([`NtCall::finish`] in `nt::call`). `ServiceFn` resolves in
/// the including module's scope.
pub fn nt_services(spec: &Spec, source: &str) -> String {
    let mut services: Vec<(&Export, u32, &str)> = spec
        .exports
        .iter()
        .filter_map(|export| match &export.implementation {
            Implementation::Syscall(path) => {
                Some((export, export.syscall_number()?, path.as_str()))
            }
            _ => None,
        })
        .collect();
    services.sort_by_key(|&(_, number, _)| number);
    let mut out = banner(source);
    writeln!(
        out,
        "/// Windows 2000's KiServiceLimit: the first number past its last system service.\n\
         pub const NT_SERVICE_LIMIT: u32 = {};\n",
        w2k::service_limit()
    )
    .unwrap();
    out.push_str(
        "/// The system services F2K serves: (number, service, argument bytes, handler), in number order,\n\
         /// the numbers Windows 2000's. A number below the limit absent from here is a service F2K does\n\
         /// not have.\n",
    );
    writeln!(
        out,
        "pub const NT_SERVICES: [(u32, &str, u32, ServiceFn); {}] = [",
        services.len()
    )
    .unwrap();
    for (export, number, _) in &services {
        writeln!(
            out,
            "    ({number:#05x}, {}, {}, {}),",
            quote(&export.name),
            export.arg_bytes(),
            export.nt_wrapper()
        )
        .unwrap();
    }
    out.push_str("];\n");
    for (export, _, path) in &services {
        out.push('\n');
        writeln!(
            out,
            "/// {}'s wrapper: the system service `{path}`.",
            export.name
        )
        .unwrap();
        writeln!(out, "#[allow(non_snake_case, unused_imports)]").unwrap();
        writeln!(
            out,
            "fn {}(frame: &mut crate::user::TrapFrame, args: &[u32]) {{",
            export.nt_wrapper()
        )
        .unwrap();
        writeln!(out, "    use crate::nt::call::*;").unwrap();
        if export.args.is_empty() {
            writeln!(out, "    let _ = args;").unwrap();
        }
        writeln!(out, "    let mut call = NtCall::new(frame);").unwrap();
        let mut call_args = vec!["&mut call".to_string()];
        call_args.extend(decode_args(export));
        writeln!(out, "    let result = {path}({});", call_args.join(", ")).unwrap();
        writeln!(out, "    call.finish(result);").unwrap();
        out.push_str("}\n");
    }
    out
}

/// The expressions a wrapper decodes `export`'s argument block (`args`, dwords) into, by the spec's
/// kinds, in argument order. A system service takes no string kinds (the spec refuses them: NT's
/// strings are UNICODE_STRINGs behind pointers).
fn decode_args(export: &Export) -> Vec<String> {
    let mut decoded = Vec::new();
    let mut word = 0usize;
    for arg in &export.args {
        let at = |offset: usize| format!("args[{}]", word + offset);
        decoded.push(match arg.kind {
            ArgKind::U32 => at(0),
            ArgKind::I32 => format!("{} as i32", at(0)),
            ArgKind::Bool => format!("{} != 0", at(0)),
            ArgKind::Handle => format!("Handle({})", at(0)),
            ArgKind::Ptr => format!("UserAddr({})", at(0)),
            ArgKind::PtrTo(pointee) => format!("UserPtr::<{}>::at({})", pointee.rust(), at(0)),
            ArgKind::U64 => format!("u64::from({}) | (u64::from({}) << 32)", at(0), at(1)),
            ArgKind::Str { .. } => {
                unreachable!("{}: a system service takes no strA or strW", export.name)
            }
        });
        word += (arg.kind.bytes() / 4) as usize;
    }
    decoded
}

/// The native exports as the spec declares them: `NATIVE_EXPORTS`, `(export, argument bytes)` in
/// file order (internal entry points left out). The bodies are the DLL's assembly; this list lets
/// a test check the kernel's view of them against the spec.
pub fn kernel_natives(spec: &Spec, source: &str) -> String {
    let natives: Vec<_> = spec.natives().into_iter().filter(|e| !e.internal).collect();
    let mut out = banner(source);
    out.push_str(
        "/// The native exports the spec declares: (export, argument bytes), in spec order.\n",
    );
    writeln!(
        out,
        "pub const NATIVE_EXPORTS: [(&str, u32); {}] = [",
        natives.len()
    )
    .unwrap();
    for export in natives {
        writeln!(
            out,
            "    ({}, {}),",
            quote(&export.name),
            export.arg_bytes()
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

/// Every export the DLL's table carries, whatever implements it: `DLL_EXPORTS`, `(export,
/// argument bytes)` in file order (internal entry points left out): the DLL's surface, its
/// forwarders into the other DLL included.
pub fn dll_exports(spec: &Spec, source: &str) -> String {
    let exports: Vec<_> = spec.exports.iter().filter(|e| !e.internal).collect();
    let mut out = banner(source);
    out.push_str("/// Every export the spec declares: (export, argument bytes), in spec order.\n");
    writeln!(
        out,
        "pub const DLL_EXPORTS: [(&str, u32); {}] = [",
        exports.len()
    )
    .unwrap();
    for export in exports {
        writeln!(
            out,
            "    ({}, {}),",
            quote(&export.name),
            export.arg_bytes()
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

/// The system-call gate's vector.
pub const SYSCALL_VECTOR: u8 = 0x2E;

/// The symbol a system service's stub carries in ntdll (the `.def` maps its `Nt` and `Zw` names to
/// it).
pub fn nt_stub_symbol(export: &str) -> String {
    format!("_f2k_nt_{export}")
}

/// A system service's stub, as Windows 2000's ntdll spells it: `mov eax, number`, `lea edx,
/// [esp+4]` (EDX = the caller's arguments), `int 2Eh`, `ret arg_bytes`.
pub fn nt_stub_bytes(number: u32, arg_bytes: u32) -> [u8; 14] {
    let mut bytes = [
        0xB8,
        0,
        0,
        0,
        0,
        0x8D,
        0x54,
        0x24,
        0x04,
        0xCD,
        SYSCALL_VECTOR,
        0xC2,
        0,
        0,
    ];
    bytes[1..5].copy_from_slice(&number.to_le_bytes());
    bytes[12..14].copy_from_slice(&(arg_bytes as u16).to_le_bytes());
    bytes
}

/// `spec`'s system services in number order: (export, number).
fn syscalls(spec: &Spec) -> Vec<(&Export, u32)> {
    let mut services: Vec<(&Export, u32)> = spec
        .exports
        .iter()
        .filter_map(|e| Some((e, e.syscall_number()?)))
        .collect();
    services.sort_by_key(|&(_, number)| number);
    services
}

/// The `ret` popping `export`'s argument block (stdcall).
fn ret(export: &Export) -> String {
    match export.arg_bytes() {
        0 => "ret".to_string(),
        bytes => format!("ret {bytes}"),
    }
}

/// The symbol a hand-written export's code carries in a DLL's assembly sources.
pub fn hand_symbol(export: &str) -> String {
    format!("_f2k_export_{export}")
}

/// `dll`'s generated bodies as Intel-syntax assembly: one global [`nt_stub_symbol`] per system
/// service its spec declares, in number order. The gate vector is the `SYSCALL_VECTOR` constant the
/// DLL's constants file sets (see `abi`).
pub fn dll_stubs(specs: &[(&str, &Spec)], dll: &str) -> String {
    let own = own_spec(specs, dll);
    let mut out = String::from(".text\n");
    for (export, number) in syscalls(own) {
        writeln!(
            out,
            ".p2align 4\n.globl {symbol}\n{symbol}:\n    mov eax, {number:#x}\n    lea edx, [esp+4]\n    int SYSCALL_VECTOR\n    {ret}",
            symbol = nt_stub_symbol(&export.name),
            ret = ret(export),
        )
        .unwrap();
    }
    out
}

/// `dll`'s module-definition file: its hand-written exports (to their code, in `hand_exports`
/// order: the order of the `.globl` lines of its assembly sources), then its system services (each
/// under its `Nt` and its `Zw` name, to its stub, in number order), then its forwarders
/// (`Name=MODULE.Export`, in spec order). An export's ordinal is its spec's when it has one (a
/// system service's Zw alias's, its `zw_ordinal`), otherwise the next free one. `hand_exports` must be exactly the spec's natives.
pub fn dll_def(
    specs: &[(&str, &Spec)],
    dll: &str,
    hand_exports: &[String],
) -> Result<String, String> {
    let own = own_spec(specs, dll);
    let mut natives: Vec<&str> = own.natives().iter().map(|e| e.name.as_str()).collect();
    let mut written: Vec<&str> = hand_exports.iter().map(String::as_str).collect();
    natives.sort();
    written.sort();
    if natives != written {
        return Err(format!(
            "{dll}: the assembly sources export {written:?}, the spec's natives are {natives:?}"
        ));
    }
    // Each line with its ordinal, when the spec gives one.
    let mut lines: Vec<(Option<u16>, String)> = Vec::new();
    for name in hand_exports {
        let export = own.export(name).expect("checked against the natives above");
        lines.push((
            export.ordinal,
            format!("{}={}", export.name, &hand_symbol(&export.name)[1..]),
        ));
    }
    for (export, _) in syscalls(own) {
        let nt = &export.name;
        let zw = w2k::zw_alias(nt);
        let symbol = &nt_stub_symbol(nt)[1..];
        lines.push((export.ordinal, format!("{nt}={symbol}")));
        lines.push((export.zw_ordinal, format!("{zw}={symbol}")));
    }
    for export in &own.exports {
        if let Implementation::Forward(target) = &export.implementation {
            lines.push((export.ordinal, format!("{}={target}", export.name)));
        }
    }
    // The next free ordinal skips every one the platform's table holds, catalogued ones included.
    let taken: Vec<u16> = own
        .exports
        .iter()
        .flat_map(|e| [e.ordinal, e.zw_ordinal])
        .flatten()
        .chain(own.catalogued.iter().map(|c| c.ordinal))
        .collect();
    let mut next = 1u16;
    let mut out = format!("LIBRARY {dll}.dll\nEXPORTS\n");
    for (ordinal, line) in lines {
        let ordinal = match ordinal {
            Some(ordinal) => ordinal,
            None => {
                while taken.contains(&next) {
                    next += 1;
                }
                next += 1;
                next - 1
            }
        };
        writeln!(out, "  {line} @{ordinal}").unwrap();
    }
    Ok(out)
}

fn own_spec<'a>(specs: &[(&str, &'a Spec)], dll: &str) -> &'a Spec {
    specs
        .iter()
        .find(|(name, _)| *name == dll)
        .map(|(_, spec)| *spec)
        .unwrap_or_else(|| panic!("no spec for {dll}"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse_spec;
    use crate::tests::SPEC;

    const NTDLL: &str = r#"
[[group]]
key = "exceptions"
title = "exceptions"

[[export]]
name = "RtlUnwind"
group = "exceptions"
args = ["ptr TargetFrame"]
impl = { native = "RtlUnwind" }

[[export]]
name = "F2kHelper"
group = "exceptions"
args = []
impl = { native = "F2kHelper" }
internal = true
"#;

    fn both() -> (Spec, Spec) {
        let kernel32 = SPEC.to_string()
            + "\n[[export]]\nname = \"RtlUnwind\"\ngroup = \"termination\"\nargs = [\"ptr TargetFrame\"]\nimpl = { forward = \"NTDLL.RtlUnwind\" }\n";
        (parse_spec(&kernel32).unwrap(), parse_spec(NTDLL).unwrap())
    }

    fn natives() -> Vec<String> {
        ["ExitProcess", "GetVersion", "GetLastError", "SetStdHandle"]
            .map(String::from)
            .to_vec()
    }

    #[test]
    fn the_dlls_check_together() {
        let (kernel32, ntdll) = both();
        let error =
            crate::check_together(&[("kernel32", &kernel32), ("ntdll", &ntdll)]).unwrap_err();
        assert!(
            error.contains("HeapAlloc: forwards to NTDLL.RtlAllocateHeap"),
            "{error}"
        );
        let ntdll = parse_spec(&format!(
            "{NTDLL}\n[[export]]\nname = \"RtlAllocateHeap\"\ngroup = \"exceptions\"\n\
             args = [\"u32 hHeap\", \"u32 dwFlags\", \"u32 dwBytes\"]\nimpl = {{ native = \"x\" }}\n"
        ))
        .unwrap();
        crate::check_together(&[("kernel32", &kernel32), ("ntdll", &ntdll)]).unwrap();
        let ntdll = parse_spec(&format!(
            "{NTDLL}\n[[export]]\nname = \"RtlAllocateHeap\"\ngroup = \"exceptions\"\n\
             args = [\"u32 hHeap\"]\nimpl = {{ native = \"x\" }}\n"
        ))
        .unwrap();
        let error =
            crate::check_together(&[("kernel32", &kernel32), ("ntdll", &ntdll)]).unwrap_err();
        assert!(error.contains("prototype differs"), "{error}");
    }

    #[test]
    fn natives_and_exports() {
        let spec = parse_spec(SPEC).unwrap();
        assert!(kernel_natives(&spec, "t").contains("(\"GetLastError\", 0),"));
        let exports = dll_exports(&spec, "t");
        assert!(exports.contains("[(&str, u32); 5]"), "{exports}");
        assert!(exports.contains("    (\"SetStdHandle\", 8),"), "{exports}");
        assert!(
            !dll_exports(&parse_spec(NTDLL).unwrap(), "t").contains("F2kHelper"),
            "internal"
        );
        assert!(
            !kernel_natives(&parse_spec(NTDLL).unwrap(), "t").contains("F2kHelper"),
            "internal"
        );
    }

    const SYSCALLS: &str = r#"
[[group]]
key = "nt"
title = "system services"

[[export]]
name = "NtOpenFile"
group = "nt"
args = ["ptr<u32> FileHandle", "u32 DesiredAccess", "ptr ObjectAttributes", "ptr IoStatusBlock", "u32 ShareAccess", "u32 OpenOptions"]
impl = { syscall = "crate::nt::file::open_file" }

[[export]]
name = "NtClose"
group = "nt"
args = ["handle Handle"]
impl = { syscall = "crate::nt::object::close" }
"#;

    #[test]
    fn system_services_take_windows_2000s_numbers_and_their_zw_names() {
        let ntdll = parse_spec(SYSCALLS).unwrap();
        let out = nt_services(&ntdll, "t");
        assert!(
            out.contains("pub const NT_SERVICE_LIMIT: u32 = 248;"),
            "{out}"
        );
        assert!(out.contains("    (0x018, \"NtClose\", 4, nt_NtClose),\n    (0x064, \"NtOpenFile\", 24, nt_NtOpenFile),"), "{out}");
        assert!(out.contains("    let result = crate::nt::object::close(&mut call, Handle(args[0]));\n    call.finish(result);"), "{out}");
        assert!(
            out.contains("UserPtr::<u32>::at(args[0]), args[1], UserAddr(args[2])"),
            "{out}"
        );
        let kernel32 = parse_spec(SPEC).unwrap();
        let specs = [("kernel32", &kernel32), ("ntdll", &ntdll)];
        let stubs = dll_stubs(&specs, "ntdll");
        assert!(
            stubs.contains("_f2k_nt_NtClose:\n    mov eax, 0x18\n    lea edx, [esp+4]\n    int SYSCALL_VECTOR\n    ret 4\n"),
            "{stubs}"
        );
        assert!(!dll_stubs(&specs, "kernel32").contains("_f2k_nt_"));
        let def = dll_def(&specs, "ntdll", &[]).unwrap();
        assert_eq!(
            def,
            "LIBRARY ntdll.dll\nEXPORTS\n  NtClose=f2k_nt_NtClose @1\n  ZwClose=f2k_nt_NtClose @2\n  \
             NtOpenFile=f2k_nt_NtOpenFile @3\n  ZwOpenFile=f2k_nt_NtOpenFile @4\n"
        );
        assert_eq!(
            nt_stub_bytes(0x18, 4),
            [0xB8, 0x18, 0, 0, 0, 0x8D, 0x54, 0x24, 0x04, 0xCD, 0x2E, 0xC2, 4, 0]
        );
    }

    /// kernel32 generates no bodies: its exports are its own code and its forwarders. The `.def`
    /// maps the hand-written exports in their sources' order, then the forwarders.
    #[test]
    fn each_dll_gets_its_stubs_and_def() {
        let (kernel32, ntdll) = both();
        let specs = [("kernel32", &kernel32), ("ntdll", &ntdll)];
        assert_eq!(dll_stubs(&specs, "kernel32"), ".text\n");
        assert_eq!(dll_stubs(&specs, "ntdll"), ".text\n");
        let def = dll_def(&specs, "kernel32", &natives()).unwrap();
        assert_eq!(
            def,
            "LIBRARY kernel32.dll\nEXPORTS\n  ExitProcess=f2k_export_ExitProcess @1\n  \
             GetVersion=f2k_export_GetVersion @2\n  GetLastError=f2k_export_GetLastError @3\n  \
             SetStdHandle=f2k_export_SetStdHandle @4\n  HeapAlloc=NTDLL.RtlAllocateHeap @16\n  \
             RtlUnwind=NTDLL.RtlUnwind @5\n"
        );
        let def = dll_def(&specs, "ntdll", &["RtlUnwind".into(), "F2kHelper".into()]).unwrap();
        assert_eq!(
            def,
            "LIBRARY ntdll.dll\nEXPORTS\n  RtlUnwind=f2k_export_RtlUnwind @1\n  \
             F2kHelper=f2k_export_F2kHelper @2\n"
        );
        assert!(dll_def(&specs, "kernel32", &[])
            .unwrap_err()
            .contains("natives"));
    }

    /// The platform's ordinals: a system service's and its Zw alias's from the spec, and an export
    /// without one takes the next ordinal no record holds (a catalogued export's included); a
    /// catalogued export is in no generated file.
    #[test]
    fn the_def_keeps_the_platforms_ordinals() {
        let text = SYSCALLS.replacen(
            "impl = { syscall = \"crate::nt::object::close\" }",
            "impl = { syscall = \"crate::nt::object::close\" }\nordinal = 7\nzw_ordinal = 9",
            1,
        ) + "\n[[export]]\nname = \"NtYieldExecution\"\nordinal = 1\n\n[[export]]\nname = \"NlsAnsiCodePage\"\nordinal = 2\ndata = true\n";
        let ntdll = parse_spec(&text).unwrap();
        assert_eq!(ntdll.catalogued.len(), 2);
        assert!(ntdll.catalogued[1].data);
        let kernel32 = parse_spec(SPEC).unwrap();
        let specs = [("kernel32", &kernel32), ("ntdll", &ntdll)];
        assert_eq!(
            dll_def(&specs, "ntdll", &[]).unwrap(),
            "LIBRARY ntdll.dll\nEXPORTS\n  NtClose=f2k_nt_NtClose @7\n  ZwClose=f2k_nt_NtClose @9\n  \
             NtOpenFile=f2k_nt_NtOpenFile @3\n  ZwOpenFile=f2k_nt_NtOpenFile @4\n"
        );
        assert!(!nt_services(&ntdll, "t").contains("NtYieldExecution"));
    }
}
