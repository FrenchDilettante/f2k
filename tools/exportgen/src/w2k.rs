//! Windows 2000's system-service numbers, in its two service tables:
//!
//! - ntoskrnl's (KiServiceTable, table 0: numbers from 0), which ntdll's `Nt*` and `Zw*` stubs load
//!   into EAX before `int 2Eh`;
//! - win32k's (W32pServiceTable, table 1: numbers from 0x1000), which user32's and gdi32's own
//!   `NtUser*` and `NtGdi*` stubs load (Windows 2000's user32 and gdi32 enter the kernel
//!   themselves, not through ntdll, and export none of those calls).
//!
//! Exports with `impl = { syscall = ... }` take their numbers from here, so a program issuing the
//! gate itself with Windows 2000's numbers reaches the same service.
//!
//! The tables (userland/ntdll/w2k-services.txt, userland/user32/w2k-services.txt) are generated by
//! scripts/gen-nt-tables.py from a public table, and are unverified against the capture machine's
//! own DLLs (GAP-NT-3).

/// ntoskrnl's table's text: `<number> <name>` lines, `#` comments.
const TABLE: &str = include_str!("../../../userland/ntdll/w2k-services.txt");

/// win32k's table's text, in the same format.
const WIN32K_TABLE: &str = include_str!("../../../userland/user32/w2k-services.txt");

/// The first number of win32k's table: table 1 in the number's bits 12-13.
pub const WIN32K_BASE: u32 = 0x1000;

/// A table's services, in number order: `(number, name)`.
fn read(table: &'static str) -> impl Iterator<Item = (u32, &'static str)> {
    table
        .lines()
        .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
        .map(|line| {
            let (number, name) = line
                .split_once(' ')
                .expect("a service line is `<number> <name>`");
            let number = u32::from_str_radix(number.trim_start_matches("0x"), 16)
                .expect("a service number is hexadecimal");
            (number, name.trim())
        })
}

/// ntoskrnl's services, in number order: `(number, name)`.
pub fn services() -> impl Iterator<Item = (u32, &'static str)> {
    read(TABLE)
}

/// win32k's services, in number order: `(number, name)`, the numbers from [`WIN32K_BASE`].
pub fn win32k_services() -> impl Iterator<Item = (u32, &'static str)> {
    read(WIN32K_TABLE)
}

/// The number of ntoskrnl's service `name` (`NtClose`), if Windows 2000 has it.
pub fn service_number(name: &str) -> Option<u32> {
    services()
        .find(|&(_, service)| service == name)
        .map(|(number, _)| number)
}

/// The number of win32k's service `name` (`NtUserGetThreadDesktop`), if Windows 2000 has it.
pub fn win32k_service_number(name: &str) -> Option<u32> {
    win32k_services()
        .find(|&(_, service)| service == name)
        .map(|(number, _)| number)
}

/// How many services ntoskrnl's table holds: KiServiceLimit, the first number past the last
/// service.
pub fn service_limit() -> u32 {
    services().map(|(number, _)| number + 1).max().unwrap_or(0)
}

/// How many services win32k's table holds: W32pServiceLimit, the first index past the last service
/// (an index is the number without the table's bits).
pub fn win32k_service_limit() -> u32 {
    win32k_services()
        .map(|(number, _)| number - WIN32K_BASE + 1)
        .max()
        .unwrap_or(0)
}

/// The `Zw` alias of ntoskrnl's service `name`: ntdll exports both names at the one stub.
pub fn zw_alias(name: &str) -> String {
    format!(
        "Zw{}",
        name.strip_prefix("Nt").expect("a service is named Nt*")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_windows_2000s() {
        assert_eq!(service_number("NtAcceptConnectPort"), Some(0));
        assert_eq!(service_number("NtClose"), Some(0x18));
        assert_eq!(service_number("NtCreateFile"), Some(0x20));
        assert_eq!(service_number("NtOpenFile"), Some(0x64));
        assert_eq!(service_number("NtWaitForSingleObject"), Some(0xEA));
        assert_eq!(service_number("NtCreateKeyedEvent"), None, "an XP service");
        assert_eq!(service_limit(), 248);
        let numbers: Vec<u32> = services().map(|(number, _)| number).collect();
        assert!(
            numbers
                .iter()
                .enumerate()
                .all(|(index, &n)| n == index as u32),
            "dense, in order"
        );
        assert_eq!(zw_alias("NtClose"), "ZwClose");
    }

    /// win32k's table: dense from 0x1000, SP4's 640 services, no name in both tables.
    #[test]
    fn the_second_table_is_win32ks() {
        assert_eq!(win32k_service_number("NtGdiAbortDoc"), Some(0x1000));
        assert_eq!(
            win32k_service_number("NtUserGetObjectInformation"),
            Some(0x119C)
        );
        assert_eq!(
            win32k_service_number("NtUserGetProcessWindowStation"),
            Some(0x119F)
        );
        assert_eq!(
            win32k_service_number("NtUserGetThreadDesktop"),
            Some(0x11A2)
        );
        assert_eq!(
            win32k_service_number("NtUserValidateTimerCallback"),
            Some(0x127F),
            "SP4's addition"
        );
        assert_eq!(win32k_service_number("NtClose"), None);
        assert_eq!(win32k_service_limit(), 640);
        assert!(win32k_services()
            .enumerate()
            .all(|(index, (n, _))| n == WIN32K_BASE + index as u32));
        assert!(win32k_services().all(|(_, name)| service_number(name).is_none()));
    }
}
