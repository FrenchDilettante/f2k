//! FoldStringW and FoldStringA: a string's characters mapped by the MAP_ flags, kernel32's own NLS
//! code as on Windows 2000.
//!
//! - MAP_FOLDCZONE folds the compatibility zone (U+F900-U+FFEF) into the characters its forms stand
//!   for: the fullwidth and halfwidth forms, the vertical and small forms, the Arabic and Hebrew
//!   presentation forms ([`COMPATIBILITY`]); the ideographic space U+3000, outside the zone, stays
//!   (the locale fixture's capture).
//! - MAP_FOLDDIGITS folds every digit into its ASCII one: the scripts' decimal digits, the
//!   superscripts and subscripts, the circled and parenthesized ones ([`DIGITS`]).
//! - MAP_COMPOSITE decomposes a precomposed Latin letter into its base letter and combining mark,
//!   and MAP_PRECOMPOSED composes the pair back ([`COMPOSED`]: Latin-1 and Latin Extended-A); a
//!   pair with no precomposed form stays as it is.
//! - MAP_EXPAND_LIGATURES spells the Latin ligatures out (æ as "ae", ß as "ss", ﬁ as "fi").
//!
//! The tables are the Unicode Character Database's, version 3.2: its compatibility and canonical
//! decompositions and its digit values. Folding comes before the expansions and the composition.
//! No flag, an unknown one, MAP_PRECOMPOSED with MAP_COMPOSITE, or MAP_EXPAND_LIGATURES with
//! either, is ERROR_INVALID_FLAGS; a count of 0, a source that is also the destination, a negative
//! size or no destination with a size is ERROR_INVALID_PARAMETER. As the NLS calls do, a count of
//! -1 takes the source through its terminator, which is mapped and counted too; a size of 0 asks
//! the size needed; a destination too short is ERROR_INSUFFICIENT_BUFFER.
//!
//! FoldStringA maps through Unicode: the source converted from the ANSI code page, mapped, and
//! converted back with the code page's best fit (a combining acute accent becomes ´, the spacing
//! accent: the capture's "e´" for é under MAP_COMPOSITE).

use core::iter::Peekable;

use rtl::codepage::{self, CodePage};

use crate::edge::{Counted, OutBuf};
use crate::error::{answer, Failure, ERROR_INVALID_FLAGS, ERROR_INVALID_PARAMETER};
use crate::heap::HeapVec;
use crate::locale::{check_destination, room, Produced};

/// The MAP_ flags.
pub const MAP_FOLDCZONE: u32 = 0x0010;
pub const MAP_PRECOMPOSED: u32 = 0x0020;
pub const MAP_COMPOSITE: u32 = 0x0040;
pub const MAP_FOLDDIGITS: u32 = 0x0080;
pub const MAP_EXPAND_LIGATURES: u32 = 0x2000;

/// Every flag FoldString takes.
const VALID_FLAGS: u32 =
    MAP_FOLDCZONE | MAP_PRECOMPOSED | MAP_COMPOSITE | MAP_FOLDDIGITS | MAP_EXPAND_LIGATURES;

/// The ligatures MAP_EXPAND_LIGATURES spells out, and their letters (a NUL ends a short one).
const LIGATURES: [(u16, [u8; 3]); 13] = [
    (0x00C6, *b"AE\0"),
    (0x00DF, *b"ss\0"),
    (0x00E6, *b"ae\0"),
    (0x0132, *b"IJ\0"),
    (0x0133, *b"ij\0"),
    (0x0152, *b"OE\0"),
    (0x0153, *b"oe\0"),
    (0xFB00, *b"ff\0"),
    (0xFB01, *b"fi\0"),
    (0xFB02, *b"fl\0"),
    (0xFB03, *b"ffi"),
    (0xFB04, *b"ffl"),
    (0xFB06, *b"st\0"),
];

/// The flags judged: ERROR_INVALID_FLAGS for none, an unknown one, or a pair that may not go
/// together.
fn check_flags(flags: u32) -> Result<(), Failure> {
    let composing = flags & (MAP_PRECOMPOSED | MAP_COMPOSITE);
    let refused = flags == 0
        || flags & !VALID_FLAGS != 0
        || composing == MAP_PRECOMPOSED | MAP_COMPOSITE
        || (flags & MAP_EXPAND_LIGATURES != 0 && composing != 0);
    if refused {
        return Err(Failure::Error(ERROR_INVALID_FLAGS));
    }
    Ok(())
}

/// What a table of runs maps `unit` to: a run (first, last, target) maps first..=last onto target
/// on; none for a unit outside every run.
fn in_runs(table: &[(u16, u16, u16)], unit: u16) -> Option<u16> {
    let at = table.partition_point(|&(_, last, _)| last < unit);
    let &(first, _, target) = table.get(at).filter(|&&(first, ..)| first <= unit)?;
    Some(target + (unit - first))
}

/// The unit MAP_FOLDCZONE and MAP_FOLDDIGITS fold `unit` into.
fn folded(flags: u32, unit: u16) -> u16 {
    let unit = match flags & MAP_FOLDCZONE {
        0 => unit,
        _ => in_runs(&COMPATIBILITY, unit).unwrap_or(unit),
    };
    match flags & MAP_FOLDDIGITS {
        0 => unit,
        _ => in_runs(&DIGITS, unit).map_or(unit, |digit| u16::from(b'0') + digit),
    }
}

/// The precomposed letter of `base` and `mark`, if any.
fn composed(base: u16, mark: u16) -> Option<u16> {
    COMPOSED
        .iter()
        .find(|&&(_, b, m)| b == base && m == mark)
        .map(|&(precomposed, ..)| precomposed)
}

/// The base letter and mark of a precomposed letter, if it is one.
fn decomposed(unit: u16) -> Option<(u16, u16)> {
    let at = COMPOSED.binary_search_by_key(&unit, |&(precomposed, ..)| precomposed);
    at.ok().map(|at| (COMPOSED[at].1, COMPOSED[at].2))
}

/// The string `units` mapped by `flags` (already judged), each unit of the result handed to `out`.
pub fn fold(flags: u32, units: impl Iterator<Item = u16>, mut out: impl FnMut(u16)) {
    let mut units: Peekable<_> = units.map(|unit| folded(flags, unit)).peekable();
    while let Some(unit) = units.next() {
        if flags & MAP_EXPAND_LIGATURES != 0 {
            if let Some((_, letters)) = LIGATURES.iter().find(|&&(ligature, _)| ligature == unit) {
                letters
                    .iter()
                    .take_while(|&&letter| letter != 0)
                    .for_each(|&letter| out(u16::from(letter)));
                continue;
            }
        }
        if flags & MAP_COMPOSITE != 0 {
            if let Some((base, mark)) = decomposed(unit) {
                out(base);
                out(mark);
                continue;
            }
        }
        if flags & MAP_PRECOMPOSED != 0 {
            if let Some(precomposed) = units.peek().and_then(|&mark| composed(unit, mark)) {
                units.next();
                out(precomposed);
                continue;
            }
        }
        out(unit);
    }
}

/// The source's count judged: ERROR_INVALID_PARAMETER for none, a count of 0 or one below -1.
fn check_source<U: Copy + Default + PartialEq>(src: &Counted<'_, U>) -> Result<(), Failure> {
    if src.is_null() || src.count() == 0 || src.count() < -1 {
        return Err(Failure::Error(ERROR_INVALID_PARAMETER));
    }
    Ok(())
}

/// FoldStringW: the source's characters mapped by the flags into the destination (see the module
/// notes); the characters written, or needed for a size of 0.
///
/// # Safety
///
/// The source holds `count` characters (a NUL-terminated string for -1); the destination `size`.
#[unsafe(export_name = "f2k_export_FoldStringW")]
pub unsafe extern "system" fn fold_string_w(
    flags: u32,
    src: *const u16,
    count: i32,
    dst: *mut u16,
    size: i32,
) -> i32 {
    let same = !src.is_null() && core::ptr::eq(src, dst);
    // SAFETY: the caller's source and destination (the contract; a negative size, which the call
    // refuses before it writes, holds none).
    let (src, out) = unsafe { (Counted::new(src, count), OutBuf::new(dst, room(size))) };
    answer(fold_wide(flags, src, out, size, same), 0)
}

/// FoldStringW's work.
fn fold_wide(
    flags: u32,
    src: Counted<'_, u16>,
    dst: OutBuf<'_, u16>,
    size: i32,
    same: bool,
) -> Result<i32, Failure> {
    check_flags(flags)?;
    check_source(&src)?;
    check_destination(&dst, size)?;
    if same {
        return Err(Failure::Error(ERROR_INVALID_PARAMETER));
    }
    let mut out = Produced::new(dst);
    fold(flags, src.units(true).iter(), |unit| out.put(unit));
    Ok(out.finish()? as i32)
}

/// FoldStringA: FoldStringW over the source converted from the ANSI code page, the result
/// converted back (see the module notes); the bytes written, or needed for a size of 0.
///
/// # Safety
///
/// As FoldStringW's, in bytes.
#[unsafe(export_name = "f2k_export_FoldStringA")]
pub unsafe extern "system" fn fold_string_a(
    flags: u32,
    src: *const u8,
    count: i32,
    dst: *mut u8,
    size: i32,
) -> i32 {
    let same = !src.is_null() && core::ptr::eq(src, dst);
    // SAFETY: as FoldStringW's.
    let (src, out) = unsafe { (Counted::new(src, count), OutBuf::new(dst, room(size))) };
    answer(fold_narrow(flags, src, out, size, same), 0)
}

/// FoldStringA's work.
fn fold_narrow(
    flags: u32,
    src: Counted<'_, u8>,
    dst: OutBuf<'_, u8>,
    size: i32,
    same: bool,
) -> Result<i32, Failure> {
    check_flags(flags)?;
    check_source(&src)?;
    check_destination(&dst, size)?;
    if same {
        return Err(Failure::Error(ERROR_INVALID_PARAMETER));
    }
    let bytes = src.units(true).bytes();
    // A byte is one character of the code page; a character expands to three at most.
    let mut wide = HeapVec::with_capacity(bytes.len())?;
    codepage::to_wide(CodePage::Ansi, bytes, false, |unit| wide.push(unit));
    let mut mapped = HeapVec::with_capacity(3 * wide.len())?;
    fold(flags, wide.iter().copied(), |unit| mapped.push(unit));
    let mut out = Produced::new(dst);
    codepage::to_narrow(CodePage::Ansi, &mapped, b'?', true, |byte| out.put(byte));
    Ok(out.finish()? as i32)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn mapped(flags: u32, units: &[u16]) -> std::vec::Vec<u16> {
        let mut out = std::vec::Vec::new();
        fold(flags, units.iter().copied(), |unit| out.push(unit));
        out
    }

    /// The fold section's W cases.
    #[test]
    fn the_captured_mappings() {
        let fullwidth = [0xFF21, 0xFF42, 0xFF13, 0x3000, 0x78, 0xFF0C];
        assert_eq!(
            mapped(MAP_FOLDCZONE, &fullwidth),
            [0x41, 0x62, 0x33, 0x3000, 0x78, 0x2C]
        );
        let digits = [0x00B2, 0x00B3, 0x00B9, 0x0661, 0x0967, 0xFF15, 0x39];
        assert_eq!(
            mapped(MAP_FOLDDIGITS, &digits),
            [0x32, 0x33, 0x31, 0x31, 0x31, 0x35, 0x39]
        );
        let decomposed = [
            0x65, 0x301, 0x20, 0x61, 0x308, 0x20, 0x6E, 0x303, 0x20, 0x78, 0x301,
        ];
        assert_eq!(
            mapped(MAP_PRECOMPOSED, &decomposed),
            [0xE9, 0x20, 0xE4, 0x20, 0xF1, 0x20, 0x78, 0x301]
        );
        assert_eq!(mapped(MAP_COMPOSITE, &decomposed), decomposed);
        let precomposed = [0xE9, 0xC5, 0xF1, 0xFC, 0x7A];
        assert_eq!(mapped(MAP_PRECOMPOSED, &precomposed), precomposed);
        assert_eq!(
            mapped(MAP_COMPOSITE, &precomposed),
            [0x65, 0x301, 0x41, 0x30A, 0x6E, 0x303, 0x75, 0x308, 0x7A]
        );
        let ligatures = [0xE6, 0xC6, 0xFB01, 0x153, 0xDF, 0x6F];
        let expanded: std::vec::Vec<u16> = "aeAEfioesso".encode_utf16().collect();
        assert_eq!(mapped(MAP_EXPAND_LIGATURES, &ligatures), expanded);
        let mixed = [0xFF21, 0xB2, 0xE9, 0xE6, 0x71];
        assert_eq!(
            mapped(MAP_FOLDCZONE, &mixed),
            [0x41, 0xB2, 0xE9, 0xE6, 0x71]
        );
        assert_eq!(
            mapped(MAP_FOLDDIGITS | MAP_COMPOSITE, &mixed),
            [0xFF21, 0x32, 0x65, 0x301, 0xE6, 0x71]
        );
        assert_eq!(
            mapped(MAP_FOLDCZONE | MAP_EXPAND_LIGATURES, &mixed),
            [0x41, 0xB2, 0xE9, 0x61, 0x65, 0x71]
        );
    }

    /// The tables are sorted, so the look-ups' searches hold.
    #[test]
    fn the_tables_are_sorted() {
        assert!(COMPOSED.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert!(DIGITS.windows(2).all(|pair| pair[0].1 < pair[1].0));
        assert!(COMPATIBILITY.windows(2).all(|pair| pair[0].1 < pair[1].0));
    }

    /// The A form: through the ANSI code page and back, the marks best-fit to their spacing forms;
    /// the size query, a short buffer and the refused flags and arguments.
    #[test]
    fn the_narrow_form() {
        let source = b"\xE9\xC5\xF1\xFCz\0";
        let mut out = [0x7Eu8; 16];
        // SAFETY: the test's source and buffer.
        let count =
            unsafe { fold_string_a(MAP_COMPOSITE, source.as_ptr(), -1, out.as_mut_ptr(), 16) };
        assert_eq!(count, 10);
        assert_eq!(&out[..10], b"e\xB4A\xB0n~u\xA8z\0");
        // SAFETY: as above.
        unsafe {
            assert_eq!(
                fold_string_a(
                    MAP_EXPAND_LIGATURES,
                    b"\xE6\xC6\x9C\xDFo\0".as_ptr(),
                    -1,
                    core::ptr::null_mut(),
                    0
                ),
                10
            );
            assert_eq!(
                fold_string_a(MAP_FOLDCZONE, b"abc\0".as_ptr(), -1, out.as_mut_ptr(), 3),
                0
            );
        }
        assert_eq!(crate::base::last_error(), 122);
        let abc = [0x61u16, 0x62, 0x63, 0];
        let mut wide = [0u16; 8];
        // SAFETY: as above.
        unsafe {
            assert_eq!(fold_string_w(0, abc.as_ptr(), -1, wide.as_mut_ptr(), 8), 0);
            assert_eq!(crate::base::last_error(), 1004);
            let both = MAP_EXPAND_LIGATURES | MAP_COMPOSITE;
            assert_eq!(
                fold_string_w(both, abc.as_ptr(), -1, wide.as_mut_ptr(), 8),
                0
            );
            assert_eq!(
                fold_string_w(MAP_FOLDCZONE, abc.as_ptr(), 0, wide.as_mut_ptr(), 8),
                0
            );
            assert_eq!(crate::base::last_error(), 87);
            assert_eq!(
                fold_string_w(MAP_FOLDCZONE, wide.as_ptr(), -1, wide.as_mut_ptr(), 8),
                0
            );
            assert_eq!(crate::base::last_error(), 87);
            assert_eq!(
                fold_string_w(MAP_FOLDCZONE, abc.as_ptr(), 3, wide.as_mut_ptr(), 8),
                3
            );
        }
    }
}

