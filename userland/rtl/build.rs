//! The kernel ABI constants the runtime's Rust code raises the gate with (`SYS_*`, the gate's
//! vector), as Rust constants: read from the kernel's sources through tools/exportgen, as the
//! system DLLs' assembly constants are (build-support/stubs.rs).

use std::fmt::Write;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let repo = manifest.join("../..");
    for relative in ["kernel/src/user/syscall.rs", "kernel/src/user/teb.rs"] {
        println!("cargo:rerun-if-changed={}", repo.join(relative).display());
    }
    let constants = exportgen::abi::kernel_constants(&repo).unwrap_or_else(|e| panic!("{e}"));
    let mut out = String::from("// Generated by rtl's build script from the kernel's sources.\n");
    for (name, value) in constants {
        writeln!(
            out,
            "#[allow(dead_code)]\npub const {name}: u32 = {value:#x};"
        )
        .unwrap();
    }
    // Windows 2000's system-service numbers, for the user-mode code that raises them itself
    // (ntdll's own runtime): `nr::<Service>`.
    out.push_str("/// Windows 2000's system-service numbers (tools/exportgen's table).\n#[allow(dead_code, non_upper_case_globals)]\npub mod nr {\n");
    for (number, name) in exportgen::w2k::services() {
        writeln!(out, "    pub const {name}: u32 = {number:#x};").unwrap();
    }
    out.push_str("}\n");
    println!(
        "cargo:rerun-if-changed={}",
        repo.join("userland/ntdll/w2k-services.txt").display()
    );
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("abi.rs");
    std::fs::write(path, out).unwrap();
}
